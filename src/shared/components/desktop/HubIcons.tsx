// Desktop hub icon set — a small, dependency-free reproduction of the
// lucide-react glyphs used by the `New design desktop/` reference. We do
// NOT add lucide-react (per scope: no new build deps); these are hand-
// transcribed lucide paths under the same 24x24 stroke grid.
//
// All icons take { size, color, fill, strokeWidth } and default to
// currentColor so callers can colour them via the parent's `color`.

import type { CSSProperties, ReactNode } from "react";

interface SvgIconProps {
  size?: number;
  color?: string;
  fill?: string;
  sw?: number;
  children?: ReactNode;
  style?: CSSProperties;
}

const Svg = ({
  size = 16,
  color = "currentColor",
  fill = "none",
  sw = 2,
  children,
  style,
}: SvgIconProps) => (
  <svg
    viewBox="0 0 24 24"
    width={size}
    height={size}
    strokeWidth={sw}
    strokeLinecap="round"
    strokeLinejoin="round"
    // `color` may be a CSS var() (theme-aware brand tokens). var() resolves
    // in CSS properties but NOT reliably in SVG presentation attributes, so
    // route stroke/fill through `style`. A literal hex still works here too.
    style={{ flexShrink: 0, stroke: color, fill, ...style }}
    aria-hidden="true"
  >
    {children}
  </svg>
);

